"""
Generate T-SQL UPDATE statements that back-fill Parts.OrderUrl from
Builds.xlsx hyperlinks (Builds + 2025 Builds sheets only).

Each UPDATE targets at most one row: it only runs when OrderUrl IS NULL
and exactly one matching Parts row is found (matched via computer Notes
sheet/row tag + Type / Manufacturer / ModelNumber / Cost).

Does NOT execute SQL — writes ImportScripts/update_orderurls.sql for review.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Optional

from openpyxl import load_workbook

from import_builds import (
    IMPORT_TAG,
    SHEET_CONFIG,
    extract_builds_sheet,
    is_tax_summary_row,
    is_tbd_part_text,
    parse_part,
    sql_num,
    sql_str,
)

WORKBOOK = Path(__file__).resolve().parent.parent / "Builds.xlsx"
OUTPUT = Path(__file__).resolve().parent / "update_orderurls.sql"

# Only these two sheets, per request.
TARGET_SHEETS = ("Builds", "2025 Builds")


def _eq_str(col: str, value: Optional[str]) -> str:
    if value is None or value == "":
        return f"{col} IS NULL"
    return f"{col} = {sql_str(value, 100)}"


def _eq_num(col: str, value) -> str:
    if value is None:
        return f"{col} IS NULL"
    # Tolerate tiny float/decimal noise from Excel.
    return f"ABS(ISNULL({col}, -999999999) - {sql_num(value)}) < 0.005"


def _computer_notes_filter(sheet: str, row: int) -> str:
    """Match Computers.Notes tags written by the importer."""
    tag = f"{sheet} row {row}"
    clauses = [f"c.Notes LIKE N'%{tag}%'"]
    # 'Builds row N' is a substring of '2025 Builds row N' / '2024 Builds row N'.
    if sheet == "Builds":
        clauses.append("c.Notes NOT LIKE N'%2025 Builds row %'")
        clauses.append("c.Notes NOT LIKE N'%2024 Builds row %'")
    return " AND ".join(clauses)


def _emit_assigned_update(
    out: list[str],
    *,
    sheet: str,
    row: int,
    computer_name: str,
    part_type: str,
    manufacturer: Optional[str],
    model_number: Optional[str],
    cost,
    order_url: str,
    index: int,
) -> None:
    url_sql = sql_str(order_url, 500)
    notes_filter = _computer_notes_filter(sheet, row)
    out.append(f"-- {index}. {sheet} row {row}: {computer_name}")
    out.append(f"--     {part_type} | {manufacturer or '—'} | {model_number or '—'}")
    out.append(";")
    out.append("WITH target AS (")
    out.append("    SELECT p.Id")
    out.append("    FROM dbo.Parts p")
    out.append("    INNER JOIN dbo.Computers c ON c.Id = p.ComputerId")
    out.append("    WHERE p.OrderUrl IS NULL")
    out.append(f"      AND {_eq_str('p.Type', part_type)}")
    out.append(f"      AND {_eq_str('p.Manufacturer', manufacturer)}")
    out.append(f"      AND {_eq_str('p.ModelNumber', model_number)}")
    out.append(f"      AND {_eq_num('p.Cost', cost)}")
    out.append(f"      AND {notes_filter}")
    out.append(")")
    out.append("UPDATE dbo.Parts")
    out.append(f"SET OrderUrl = {url_sql}")
    out.append("WHERE Id IN (SELECT Id FROM target)")
    out.append("  AND (SELECT COUNT(*) FROM target) = 1;")
    out.append("")


def _emit_unassigned_update(
    out: list[str],
    *,
    sheet: str,
    row: int,
    part_type: str,
    manufacturer: Optional[str],
    model_number: Optional[str],
    cost,
    order_url: str,
    index: int,
) -> None:
    url_sql = sql_str(order_url, 500)
    out.append(f"-- {index}. {sheet} row {row} (unassigned inventory)")
    out.append(f"--     {part_type} | {manufacturer or '—'} | {model_number or '—'}")
    out.append(";")
    out.append("WITH target AS (")
    out.append("    SELECT p.Id")
    out.append("    FROM dbo.Parts p")
    out.append("    WHERE p.OrderUrl IS NULL")
    out.append("      AND p.ComputerId IS NULL")
    out.append(f"      AND p.Notes LIKE N'%{IMPORT_TAG}%'")
    out.append(f"      AND {_eq_str('p.Type', part_type)}")
    out.append(f"      AND {_eq_str('p.Manufacturer', manufacturer)}")
    out.append(f"      AND {_eq_str('p.ModelNumber', model_number)}")
    out.append(f"      AND {_eq_num('p.Cost', cost)}")
    out.append(")")
    out.append("UPDATE dbo.Parts")
    out.append(f"SET OrderUrl = {url_sql}")
    out.append("WHERE Id IN (SELECT Id FROM target)")
    out.append("  AND (SELECT COUNT(*) FROM target) = 1;")
    out.append("")


def main() -> None:
    if not WORKBOOK.is_file():
        raise SystemExit(f"Workbook not found: {WORKBOOK}")

    print(f"Loading {WORKBOOK} ...")
    wb = load_workbook(WORKBOOK, data_only=False)

    lines: list[str] = []
    W = lines.append
    W("/* ---------------------------------------------------------------------")
    W(" *  Back-fill Parts.OrderUrl from Builds.xlsx hyperlinks")
    W(" *  Sheets: Builds, 2025 Builds only")
    W(" *  Generated by generate_orderurl_updates.py — review before running.")
    W(" *")
    W(" *  Each UPDATE:")
    W(" *    - sets OrderUrl from the sheet HYPERLINK / hyperlink target")
    W(" *    - only matches rows where OrderUrl IS NULL")
    W(" *    - only applies when exactly one matching Parts row is found")
    W(" * --------------------------------------------------------------------- */")
    W("")
    W("SET NOCOUNT ON;")
    W("SET XACT_ABORT ON;")
    W("BEGIN TRAN;")
    W("")

    n_with_url = 0
    n_skipped_no_url = 0
    n_assigned = 0
    n_unassigned = 0
    index = 0

    for sheet_name in TARGET_SHEETS:
        cfg = SHEET_CONFIG[sheet_name]
        ws = wb[sheet_name]
        print(f"  processing {sheet_name!r} ...")
        computers, unassigned = extract_builds_sheet(ws, cfg)

        W(f"-- ========== {sheet_name} ({len(computers)} computers) ==========")
        W("")

        for c in computers:
            for p in c.parts:
                if not p.order_url:
                    n_skipped_no_url += 1
                    continue
                n_with_url += 1
                n_assigned += 1
                index += 1
                _emit_assigned_update(
                    lines,
                    sheet=sheet_name,
                    row=c.row,
                    computer_name=c.name,
                    part_type=p.part_type,
                    manufacturer=p.manufacturer,
                    model_number=p.model_number,
                    cost=p.cost,
                    order_url=p.order_url,
                    index=index,
                )

        # Unassigned inventory (Builds sheet only — import_unassigned).
        if cfg.get("import_unassigned"):
            W(f"-- ========== {sheet_name} unassigned parts ==========")
            W("")
            year = cfg["year"]
            import datetime as _dt
            today = _dt.date.today()
            sale_year = year
            sale_month = today.month if today.year == year else 12

            for row in range(2, ws.max_row + 1):
                if is_tax_summary_row(ws, row, cfg):
                    continue
                status_letter = ws.cell(row=row, column=cfg["col_status"]).value
                if isinstance(status_letter, str):
                    status_letter = status_letter.strip()
                if status_letter:
                    continue
                for pt, cinfo, cprice in cfg["part_pairs"]:
                    info_cell = ws.cell(row=row, column=cinfo)
                    info_val = info_cell.value
                    if info_val in (None, ""):
                        continue
                    if is_tbd_part_text(str(info_val)):
                        continue
                    p = parse_part(
                        pt,
                        info_cell,
                        ws.cell(row=row, column=cprice) if cprice else None,
                        sale_year,
                        sale_month,
                    )
                    if p is None:
                        continue
                    if p.part_type == "misc":
                        p.part_type = "ram"
                    if not p.order_url:
                        n_skipped_no_url += 1
                        continue
                    n_with_url += 1
                    n_unassigned += 1
                    index += 1
                    _emit_unassigned_update(
                        lines,
                        sheet=sheet_name,
                        row=row,
                        part_type=p.part_type,
                        manufacturer=p.manufacturer,
                        model_number=p.model_number,
                        cost=p.cost,
                        order_url=p.order_url,
                        index=index,
                    )

    W("COMMIT;")
    W("")
    W(f"-- Generated {index} UPDATE statements")
    W(f"--   with OrderUrl from sheet: {n_with_url}")
    W(f"--   assigned: {n_assigned}, unassigned: {n_unassigned}")
    W(f"--   sheet parts skipped (no hyperlink): {n_skipped_no_url}")

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    print(f"  UPDATEs: {index} (assigned={n_assigned}, unassigned={n_unassigned})")
    print(f"  skipped (no URL on sheet): {n_skipped_no_url}")


if __name__ == "__main__":
    # Allow running from repo root or ImportScripts/
    os.chdir(Path(__file__).resolve().parent)
    main()
